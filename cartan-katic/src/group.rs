#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn amplitude_counts_match_the_symmetry() {
        assert_eq!(AxialApolar::N_AMPLITUDES, 1);
        assert_eq!(AxialPolar::N_AMPLITUDES, 1);
        assert_eq!(<Dicyclic<2> as SymmetryGroup>::N_AMPLITUDES, 2);
    }

    #[test]
    fn dicyclic_order_is_four_k() {
        assert_eq!(<Dicyclic<2> as SymmetryGroup>::ORDER, Some(8));
        assert_eq!(<Dicyclic<3> as SymmetryGroup>::ORDER, Some(12));
        assert_eq!(Dicyclic::<2>::elements().count(), 8);
        assert_eq!(Dicyclic::<3>::elements().count(), 12);
    }

    const TOL: f64 = 1e-10;

    fn near(a: &Rotor3, b: &Rotor3) -> bool {
        dist_sq(a, b) < TOL * TOL
    }

    /// Order, distinctness, unit norm, closure, and inverses, for any finite
    /// group. A construction that is not a group fails at least one of these.
    fn check_group_axioms<H: SymmetryGroup>(name: &str) {
        let g: Vec<Rotor3> = H::elements().collect();
        let order = H::ORDER.unwrap_or_else(|| panic!("{name} has no order"));
        assert_eq!(g.len(), order, "{name}: element count");

        for (i, a) in g.iter().enumerate() {
            let n = (a.w * a.w + a.x * a.x + a.y * a.y + a.z * a.z).sqrt();
            assert!((n - 1.0).abs() < 1e-12, "{name}: element {i} has norm {n}");
            for (j, b) in g.iter().enumerate() {
                assert!(
                    i == j || !near(a, b),
                    "{name}: elements {i} and {j} coincide"
                );
            }
        }

        assert!(
            g.iter().any(|e| near(e, &Rotor3::IDENTITY)),
            "{name}: identity missing"
        );

        for (i, a) in g.iter().enumerate() {
            for (j, b) in g.iter().enumerate() {
                let c = a.compose(b);
                assert!(
                    g.iter().any(|e| near(e, &c)),
                    "{name}: product of {i} and {j} left the group"
                );
            }
            let inv = a.reverse();
            assert!(
                g.iter().any(|e| near(e, &inv)),
                "{name}: element {i} has no inverse in the group"
            );
        }
    }

    #[test]
    fn cyclic_is_a_group() {
        check_group_axioms::<Cyclic<1>>("Cyclic<1>");
        check_group_axioms::<Cyclic<2>>("Cyclic<2>");
        check_group_axioms::<Cyclic<3>>("Cyclic<3>");
        check_group_axioms::<Cyclic<6>>("Cyclic<6>");
    }

    #[test]
    fn dicyclic_is_a_group() {
        check_group_axioms::<Dicyclic<1>>("Dicyclic<1>");
        check_group_axioms::<Dicyclic<2>>("Dicyclic<2>");
        check_group_axioms::<Dicyclic<3>>("Dicyclic<3>");
        check_group_axioms::<Dicyclic<5>>("Dicyclic<5>");
    }

    #[test]
    fn polyhedral_are_groups() {
        check_group_axioms::<BinaryTetrahedral>("2T");
        check_group_axioms::<BinaryOctahedral>("2O");
        check_group_axioms::<BinaryIcosahedral>("2I");
    }

    #[test]
    fn minus_one_is_present_exactly_when_expected() {
        let minus = Rotor3 {
            w: -1.0,
            x: 0.0,
            y: 0.0,
            z: 0.0,
        };
        let has = |v: Vec<Rotor3>| v.iter().any(|e| near(e, &minus));
        assert!(
            !has(Cyclic::<3>::elements().collect()),
            "odd cyclic must omit -1"
        );
        assert!(
            has(Cyclic::<4>::elements().collect()),
            "even cyclic must contain -1"
        );
        assert!(has(Dicyclic::<2>::elements().collect()));
        assert!(has(BinaryTetrahedral::elements().collect()));
        assert!(has(BinaryOctahedral::elements().collect()));
        assert!(has(BinaryIcosahedral::elements().collect()));
    }

    #[test]
    fn explicit_lists_agree_with_generated_closure() {
        // 2T is generated by i and (1+i+j+k)/2; 2O by 2T's generators plus
        // (1+i)/sqrt(2); 2I is checked by closing on two of its own elements.
        let h = 0.5;
        let i = Rotor3 {
            w: 0.0,
            x: 1.0,
            y: 0.0,
            z: 0.0,
        };
        let omega = Rotor3 {
            w: h,
            x: h,
            y: h,
            z: h,
        };
        let t = closure(&[i, omega], TOL, 200).expect("2T closure is finite");
        assert_eq!(t.len(), 24, "2T generated order");

        let r = core::f64::consts::FRAC_1_SQRT_2;
        let s = Rotor3 {
            w: r,
            x: r,
            y: 0.0,
            z: 0.0,
        };
        let o = closure(&[i, omega, s], TOL, 400).expect("2O closure is finite");
        assert_eq!(o.len(), 48, "2O generated order");

        for e in binary_tetrahedral_elements() {
            assert!(t.iter().any(|g| near(g, &e)), "2T list is not the closure");
        }
        for e in binary_octahedral_elements() {
            assert!(o.iter().any(|g| near(g, &e)), "2O list is not the closure");
        }
    }

    #[test]
    fn contains_and_canonical_behave() {
        for e in Dicyclic::<3>::elements() {
            assert!(Dicyclic::<3>::contains(&e, TOL));
        }
        let off = Rotor3 {
            w: 0.3,
            x: 0.4,
            y: 0.5,
            z: core::f64::consts::FRAC_1_SQRT_2,
        };
        assert!(!Dicyclic::<3>::contains(&off, TOL));

        let r = Rotor3 {
            w: 0.6,
            x: 0.8,
            y: 0.0,
            z: 0.0,
        };
        let c = Dicyclic::<3>::canonical(r);
        assert!(
            near(&c, &Dicyclic::<3>::canonical(c)),
            "canonical is not idempotent"
        );
        for h in Dicyclic::<3>::elements() {
            let moved = r.compose(&h);
            assert!(
                near(&Dicyclic::<3>::canonical(moved), &c),
                "canonical is not constant on the orbit"
            );
        }
    }

    #[test]
    fn group_table_matches_the_iterator() {
        let table = GroupTable::<Dicyclic<3>>::new();
        let direct: Vec<Rotor3> = Dicyclic::<3>::elements().collect();
        assert_eq!(table.elements().len(), direct.len());
        for (a, b) in table.elements().iter().zip(direct.iter()) {
            assert!(near(a, b));
        }
    }
}
