/// The subgroup generated by `gens`, closed under multiplication.
///
/// Returns `None` when the closure exceeds `cap`, which means the generators do
/// not generate a finite group. Public so a caller adding a `SymmetryGroup`
/// implementation can build its element list from generators and check the
/// order rather than typing a table.
#[must_use]
pub fn closure(gens: &[Rotor3], tol: f64, cap: usize) -> Option<Vec<Rotor3>> {
    let mut out: Vec<Rotor3> = vec![Rotor3::IDENTITY];
    let mut frontier: Vec<Rotor3> = vec![Rotor3::IDENTITY];
    while !frontier.is_empty() {
        let mut next = Vec::new();
        for f in &frontier {
            for g in gens {
                let c = f.compose(g);
                if !out.iter().any(|o| dist_sq(o, &c) < tol * tol) {
                    out.push(c);
                    next.push(c);
                    if out.len() > cap {
                        return None;
                    }
                }
            }
        }
        frontier = next;
    }
    Some(out)
}

/// The 24 unit Hurwitz quaternions: the binary tetrahedral group.
fn binary_tetrahedral_elements() -> Vec<Rotor3> {
    let mut v = Vec::with_capacity(24);
    for i in 0..4 {
        for sign in [1.0_f64, -1.0] {
            let mut c = [0.0; 4];
            c[i] = sign;
            v.push(Rotor3 {
                w: c[0],
                x: c[1],
                y: c[2],
                z: c[3],
            });
        }
    }
    for m in 0..16u8 {
        let s = |b: u8| if m >> b & 1 == 0 { 0.5 } else { -0.5 };
        v.push(Rotor3 {
            w: s(0),
            x: s(1),
            y: s(2),
            z: s(3),
        });
    }
    v
}

/// The 48 elements of the binary octahedral group: the Hurwitz units plus the
/// 24 quaternions `(+/- e_a +/- e_b) / sqrt(2)` for `a < b`.
fn binary_octahedral_elements() -> Vec<Rotor3> {
    let mut v = binary_tetrahedral_elements();
    let r = core::f64::consts::FRAC_1_SQRT_2;
    for a in 0..4 {
        for b in (a + 1)..4 {
            for sa in [r, -r] {
                for sb in [r, -r] {
                    let mut c = [0.0; 4];
                    c[a] = sa;
                    c[b] = sb;
                    v.push(Rotor3 {
                        w: c[0],
                        x: c[1],
                        y: c[2],
                        z: c[3],
                    });
                }
            }
        }
    }
    v
}

/// The 120 icosians: the 24 Hurwitz units plus the 96 even permutations of
/// `(0, +/-1, +/-1/phi, +/-phi) / 2`.
fn binary_icosahedral_elements() -> Vec<Rotor3> {
    let mut v = binary_tetrahedral_elements();
    let phi = (1.0 + 5.0_f64.sqrt()) / 2.0;
    let base = [0.0, 0.5, 0.5 / phi, 0.5 * phi];
    // The 12 even permutations of four symbols.
    const EVEN: [[usize; 4]; 12] = [
        [0, 1, 2, 3],
        [0, 2, 3, 1],
        [0, 3, 1, 2],
        [1, 0, 3, 2],
        [1, 2, 0, 3],
        [1, 3, 2, 0],
        [2, 0, 1, 3],
        [2, 1, 3, 0],
        [2, 3, 0, 1],
        [3, 0, 2, 1],
        [3, 1, 0, 2],
        [3, 2, 1, 0],
    ];
    for p in EVEN {
        for m in 0..8u8 {
            let mut c = [0.0; 4];
            let mut bit = 0;
            for slot in 0..4 {
                let val = base[p[slot]];
                if val == 0.0 {
                    c[slot] = 0.0;
                } else {
                    c[slot] = if m >> bit & 1 == 0 { val } else { -val };
                    bit += 1;
                }
            }
            v.push(Rotor3 {
                w: c[0],
                x: c[1],
                y: c[2],
                z: c[3],
            });
        }
    }
    v
}

/// A precomputed group table.
///
/// `elements()` recomputes on every call by design: a `static` cache inside a
/// generic function is shared across every monomorphisation in Rust, so a
/// cache keyed that way would hand `Dicyclic<3>` the elements of `Dicyclic<2>`.
/// Hot paths build one of these instead and hold it.
#[derive(Clone, Debug)]
pub struct GroupTable<H: SymmetryGroup> {
    elements: Vec<Rotor3>,
    _marker: core::marker::PhantomData<H>,
}

impl<H: SymmetryGroup> GroupTable<H> {
    /// Enumerate the group once.
    #[must_use]
    pub fn new() -> Self {
        Self {
            elements: H::elements().collect(),
            _marker: core::marker::PhantomData,
        }
    }

    /// The enumerated elements.
    #[must_use]
    pub fn elements(&self) -> &[Rotor3] {
        &self.elements
    }
}

impl<H: SymmetryGroup> Default for GroupTable<H> {
    fn default() -> Self {
        Self::new()
    }
}

// --- Cyclic ------------------------------------------------------------------

/// The cyclic group of order `N` inside `SU(2)`, generated by
/// `cos(2 pi / N) + sin(2 pi / N) e23`.
///
/// Contains `-1` only when `N` is even, so `Cyclic<N>` with odd `N` maps
/// isomorphically onto a rotation group and is not a binary lift.
#[derive(Clone, Copy, Debug, Default)]
pub struct Cyclic<const N: usize>;

impl<const N: usize> SymmetryGroup for Cyclic<N> {
    type Amplitudes = [f64; 1];
    const N_AMPLITUDES: usize = 1;
    const INVARIANT_RANK: usize = N;
    const ORDER: Option<usize> = Some(N);

    fn elements() -> impl Iterator<Item = Rotor3> {
        (0..N).map(move |m| {
            let theta = 2.0 * core::f64::consts::PI * (m as f64) / (N as f64);
            let (s, c) = theta.sin_cos();
            Rotor3 {
                w: c,
                x: s,
                y: 0.0,
                z: 0.0,
            }
        })
    }

    fn contains(r: &Rotor3, tol: f64) -> bool {
        contains_by_orbit::<Self>(r, tol)
    }

    fn canonical(r: Rotor3) -> Rotor3 {
        canonical_by_orbit::<Self>(r)
    }

    fn kind() -> PointGroupKind {
        PointGroupKind::Cyclic(N)
    }
}

